def plan() -> tuple[list[Shot], float, float]:
    beats = json.loads(BEATS.read_text(encoding="utf-8"))
    sec0, sec1 = beats["section"]
    grid = [c - sec0 for c in beats["section_cuts"]]
    span = sec1 - sec0

    prev, want_acc = 0.0, 0.0
    for shot in S:
        want_acc += shot.want
        boundary = snap(want_acc, prev + 0.5, grid)
        shot.at, shot.dur = round(prev, 3), round(boundary - prev, 4)
        prev = boundary
    if prev < span:
        S[-1].dur = round(S[-1].dur + (span - prev), 4)
        prev = span
    assert prev <= span + 1e-6, f"overrun by {prev - span:.2f}s"

    # clamp video in-points
    lens: dict[str, float] = {}
    for shot in S:
        if shot.kind != "video":
            continue
        if shot.src not in lens:
            lens[shot.src] = probe_duration(TAKES / f"{shot.src}.mp4")
        if shot.inn + shot.dur > lens[shot.src] - 0.05:
            shot.inn = max(0.0, lens[shot.src] - shot.dur - 0.05)
    return S, sec0, span


def show_plan(sec0: float, span: float) -> None:
    print(f"section {sec0:.2f} -> {sec0 + span:.2f} ({span:.2f}s), {len(S)} shots")
    for i, s in enumerate(S, 1):
        kind = f"{s.kind}/{s.src or 'card'}"
        print(f"{i:>3} {s.at:>7.2f} {s.dur:>6.2f}  {kind:<26} {s.label}")
    total = sum(s.dur for s in S)
    print(f"total {total:.2f}s | avg {total / len(S):.2f}s")


