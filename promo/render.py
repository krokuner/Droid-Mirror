def esc(text: str) -> str:
    return text.replace(",", "\\,")


def label_chain(label: str) -> str:
    if not label:
        return ""
    return (
        f"drawtext=fontfile={FONT_LABEL}:fontsize=26:fontcolor=white@0.92:"
        f"box=1:boxcolor=black@0.5:boxborderw=14:text='{esc(label)}':x=64:y=64:"
        f"alpha='min(1,max(0,(t-0.12)/0.3))',"
    )


def text_chain(text: str, size: int, y: int, delay: float) -> str:
    return (
        f"drawtext=fontfile={FONT_TITLE}:fontsize={size}:fontcolor=white:"
        f"text='{esc(text)}':x=(w-text_w)/2:y={y}:"
        f"alpha='min(1,max(0,(t-{delay})/0.5))',"
    )


def shot_args(shot: Shot) -> tuple[list[str], str]:
    """Build the ffmpeg args for one shot. Returns (input args, filter graph)."""
    d = shot.dur
    pre = f"crop={shot.crop}," if shot.crop else ""
    args: list[str] = []

    if shot.kind == "card":
        args += ["-f", "lavfi", "-i",
                 f"color=c=0x0a0e13:s={W}x{H}:r={FPS}:d={d}"]
        chain = "drawgrid=w=120:h=120:t=1:c=0xFFFFFF@0.05,setsar=1"
        for text, size, y, delay in shot.lines:
            chain += "," + text_chain(text, size, y, delay).rstrip(",")
        if shot.cursor:
            x0, y0, _, _, _, _ = shot.cursor
            args += ["-loop", "1", "-framerate", str(FPS), "-t", f"{d}", "-i", str(ART / "cursor.png")]
            graph = (
                f"[0:v]{chain}[c];"
                f"[c][1:v]overlay=x={x0}:y={y0},format=yuv420p[v]"
            )
        else:
            graph = f"[0:v]{chain},format=yuv420p[v]"
        return args, graph

    if shot.kind == "still":
        src = TAKES / f"{shot.src}.png"
        args += ["-loop", "1", "-framerate", str(FPS), "-t", f"{d}", "-i", str(src)]
        F = max(1, round(d * FPS))
        z = f"{shot.z0}+({shot.z1}-{shot.z0})*on/{F}"
        zp = (f"{UP},zoompan=z='{z}':x='(iw-iw/zoom)*{shot.ax}':"
              f"y='(ih-ih/zoom)*{shot.ay}':d=1:s={W}x{H}:fps={FPS}[nz]")
        graph = f"[0:v]{BLUR.format(pre=pre)}{zp}"
        need = 1
        last = "[nz]"
        if shot.cursor and shot.ring:
            x0, y0, x1, y1, t0, t1 = shot.cursor
            args += ["-loop", "1", "-framerate", str(FPS), "-t", f"{d}", "-i", str(ART / "cursor.png")]
            args += ["-loop", "1", "-framerate", str(FPS), "-t", f"{d}", "-i", str(ART / "ring.png")]
            need = 3
            rx, ry, rat = shot.ring
            cx = f"{x0}+({x1}-{x0})*min(max((t-{t0})/({t1}-{t0}),0),1)"
            cy = f"{y0}+({y1}-{y0})*min(max((t-{t0})/({t1}-{t0}),0),1)"
            graph += (
                f";[1:v]null[cu];[2:v]fade=t=in:st={rat}:d=0.08:alpha=1,"
                f"fade=t=out:st={rat + 0.1}:d=0.35:alpha=1[rg];"
                f"{last}[cu]overlay=x='{cx}':y='{cy}':eval=frame[o1];"
                f"[o1][rg]overlay=x={rx - 36}:y={ry - 36}:eval=frame[o2]"
            )
            last = "[o2]"
        graph += f";{last}{label_chain(shot.label)}format=yuv420p[v]"
        return args, graph

    # video
    src = TAKES / f"{shot.src}.mp4"
    args += ["-ss", f"{shot.inn:.3f}", "-t", f"{d:.3f}", "-i", str(src)]
    graph = f"[0:v]{BLUR.format(pre=pre)}{label_chain(shot.label)}format=yuv420p[v]"
    return args, graph


def render_shot(shot: Shot, idx: int) -> Path:
    out = SHOTS / f"s{idx:02d}.mp4"
    in_args, graph = shot_args(shot)
    cmd = [
        str(FFMPEG), "-hide_banner", "-loglevel", "error",
        *in_args,
        "-filter_complex", graph, "-map", "[v]",
        "-r", str(FPS), "-c:v", "libx264", "-preset", "ultrafast", "-crf", "17",
        "-y", str(out),
    ]
    p = run(cmd)
    if p.returncode != 0 or not out.exists():
        raise RuntimeError(f"shot {idx} ({shot.kind}/{shot.src or 'card'}) failed:\n{p.stderr[-800:]}")
    return out


def still_frame(idx: int, at: float) -> None:
    out = PREVIEW / f"s{idx:02d}.png"
    run([str(FFMPEG), "-hide_banner", "-loglevel", "error",
         "-ss", f"{at:.2f}", "-i", str(SHOTS / f"s{idx:02d}.mp4"),
         "-frames:v", "1", "-vf", "scale=960:-2", "-y", str(out)])


def build(shots: list[Shot], sec0: float) -> None:
    SHOTS.mkdir(exist_ok=True)
    PREVIEW.mkdir(exist_ok=True)
    parts = []
    for i, shot in enumerate(shots, 1):
        parts.append(render_shot(shot, i))
        still_frame(i, max(0.0, shot.dur * 0.6))
        print(f"shot {i:02d} ok  {shot.dur:5.2f}s  {shot.kind}/{shot.src or 'card'}")
    total = sum(s.dur for s in shots)

    lst = SHOTS / "concat.txt"
    lst.write_text("".join(f"file '{p.as_posix()}'\n" for p in parts), encoding="utf-8")
    master = SHOTS / "master.mp4"
    p = run([str(FFMPEG), "-hide_banner", "-loglevel", "error",
             "-f", "concat", "-safe", "0", "-i", str(lst),
             "-c", "copy", "-y", str(master)])
    if p.returncode != 0:
        raise RuntimeError(f"concat failed:\n{p.stderr[-600:]}")

    beats = json.loads(BEATS.read_text(encoding="utf-8"))
    track = Path(beats["track"])
    fade_at = max(0.0, total - 1.3)
    p = run([
        str(FFMPEG), "-hide_banner", "-loglevel", "error",
        "-i", str(master),
        "-ss", f"{sec0:.3f}", "-i", str(track),
        "-map", "0:v", "-map", "1:a",
        "-c:v", "copy", "-c:a", "aac", "-b:a", "192k",
        "-af", f"afade=t=out:st={fade_at:.3f}:d=1.3",
        "-t", f"{total:.3f}", "-movflags", "+faststart",
        "-y", str(OUT),
    ])
    if p.returncode != 0:
        raise RuntimeError(f"mux failed:\n{p.stderr[-600:]}")
    print(f"wrote {OUT}  {OUT.stat().st_size / 1e6:.1f} MB  {total:.2f}s")


def main() -> None:
    shots, sec0, span = plan()
    show_plan(sec0, span)
    if "--plan" in sys.argv:
        return
    build(shots, sec0)


if __name__ == "__main__":
    main()
