"""render.py — the whole promo, vibe-coded. No recording, no windows, no focus.

Every shot is generated by code from assets on disk:
  * stills  -> app states (grabs + extracted frames) with code-driven camera moves,
               a code-drawn cursor glide, a click ring, and captions
  * videos  -> the real captures already on disk, re-framed
  * cards   -> drawn from scratch in ffmpeg (dark, grid lines, typography)

Cut boundaries snap onto beats.json's section cut grid, so every cut lands on a
beat of "crush" by construction. Output: promo/DroidMirror_promo.mp4

Usage (.venv python):
  python render.py            full render
  python render.py --plan     print the cut sheet only
"""

